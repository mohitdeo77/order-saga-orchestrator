CREATE TABLE saga_instances (
    id               UUID PRIMARY KEY,
    idempotency_key  VARCHAR(100)             NOT NULL,
    request_hash     VARCHAR(64)              NOT NULL,
    customer_id      VARCHAR(100)             NOT NULL,
    total_amount     NUMERIC(12, 2)           NOT NULL,
    status           VARCHAR(20)              NOT NULL,
    current_step     VARCHAR(30)              NOT NULL,
    failure_reason   VARCHAR(1000),
    attempt          INT                      NOT NULL,
    next_attempt_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    locked_until     TIMESTAMP WITH TIME ZONE,
    lease_owner      UUID,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    version          BIGINT                   NOT NULL,
    CONSTRAINT uq_saga_idempotency_key UNIQUE (idempotency_key)
);

-- Recovery job: "in-flight sagas whose next attempt is due"
CREATE INDEX idx_saga_recovery ON saga_instances (status, next_attempt_at);

CREATE TABLE saga_items (
    saga_id     UUID           NOT NULL REFERENCES saga_instances (id),
    sku         VARCHAR(50)    NOT NULL,
    quantity    INT            NOT NULL,
    unit_price  NUMERIC(12, 2) NOT NULL
);

CREATE INDEX idx_saga_items_saga ON saga_items (saga_id);

-- Append-only audit trail of every step attempt and its result
CREATE TABLE saga_step_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    saga_id     UUID                     NOT NULL REFERENCES saga_instances (id),
    step        VARCHAR(30)              NOT NULL,
    phase       VARCHAR(20)              NOT NULL,
    result      VARCHAR(20)              NOT NULL,
    detail      VARCHAR(1000),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_saga_step_log_saga ON saga_step_log (saga_id);
